def _token_matchconds(alias: str, text: str, max_tokens: int = 4) -> str:
    """Условия ПОДОБНО для НЕЗАВИСИМОГО совпадения всех токенов (порядок неважен):
    'масляный фильтр' найдёт 'Фильтр масляный'. Каждый токен ищется в Наименовании
    ИЛИ Артикуле (цифровые токены — артикулы). Кавычки удвоены: фрагмент
    встраивается внутрь BSL-строки Запрос.Текст."""
    safe = _lemmatize(_sanitize(text))
    tokens = [t for t in re.split(r"\s+", safe) if t][:max_tokens]
    if not tokens:
        tokens = ["%"]
    conds = []
    for t in tokens:
        like = f'""%{t}%""'
        if alias.startswith("Номенклатура"):
            conds.append(
                f"(ВРЕГ({alias}.Наименование) ПОДОБНО ВРЕГ({like}) "
                f"ИЛИ ВРЕГ({alias}.Артикул) ПОДОБНО ВРЕГ({like}))"
            )
        else:
            conds.append(f"ВРЕГ({alias}.Наименование) ПОДОБНО ВРЕГ({like})")
    return " И ".join(conds)


