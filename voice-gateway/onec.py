def _build_part_message(branch: str, fields: list, vehicle: str, qty: int) -> str:
    """Голосовое сообщение по результату request_part."""
    n = _plural(qty, "штука", "штуки", "штук")
    if branch == "B1":
        repair = fields[0]
        return (
            f"Запчасть есть на складе инженера. Создан заказ на ремонт № {repair}: "
            f"{fields[2]} — {qty} {n}, техника {fields[1]}."
        )
    if branch == "B2":
        repair, move = fields[0], fields[1]
        posted = len(fields) > 6 and fields[6].startswith("пров")
        tail = "" if posted else " Перемещение ожидает проведения в 1С."
        return (
            f"На складе инженера запчасти нет, но есть на складе текущего ОП "
            f"({fields[5]} шт). Создан заказ на ремонт № {repair} и перемещение № {move} "
            f"на склад инженера: {fields[3]} — {qty} {n}.{tail}"
        )
    if branch == "B3":
        repair, order_move, move = fields[0], fields[1], fields[2]
        posted = len(fields) > 7 and fields[7].startswith("пров")
        tail = "" if posted else " Перемещение ожидает проведения в 1С."
        return (
            f"Запчасть есть только на складе другого ОП ({fields[6]} шт). Создан заказ "
            f"на ремонт № {repair}, заказ на перемещение № {order_move} и перемещение "
            f"№ {move} на склад инженера: {fields[4]} — {qty} {n}.{tail}"
        )
    if branch == "B4":
        return (
            f"Запчасти ни на одном складе нет. Создан заказ поставщику № {fields[0]}: "
            f"{fields[2]} — {qty} {n}, для техники {fields[1]}."
        )
    return "; ".join(fields) if fields else vehicle


def request_part(item: str, vehicle: str, quantity: int) -> dict:
    """Кейс «запчасть для техники»: подобрать технику, проверить склады
    (инженер → текущее ОП → другое ОП) и создать нужные документы.

    Контракт: {found, vehicle, branch, docs, quantity, message, source}."""
    if not _sanitize(item) or not _sanitize(vehicle):
        return {
            "found": False,
            "vehicle": vehicle,
            "branch": "BAD_INPUT",
            "docs": [],
            "quantity": quantity,
            "message": "Не удалось понять запчасть или технику. Попробуйте иначе.",
            "source": "1c",
        }
    data = execute_code(_build_part_request_code(item, vehicle, quantity))
    parts = data.split("|")
    head = parts[0] if parts else ""
    rest = [p.strip() for p in parts[1:]]
    qty = max(1, int(quantity))
    if head in ("NO_PART",):
        return {
            "found": False,
            "vehicle": vehicle,
            "branch": head,
            "docs": [],
            "quantity": qty,
            "message": f"Запчасть '{item}' не найдена в справочнике 1С.",
            "source": "1c",
        }
    if head == "NO_VEHICLE":
        known = rest[0] if rest else ""
        names = [v.strip() for v in known.split(";") if v.strip()]
        list_phrase = ", ".join(names[:4])
        return {
            "found": False,
            "vehicle": vehicle,
            "branch": head,
            "docs": [],
            "quantity": qty,
            "message": (
                f"Техника '{vehicle}' не найдена. В базе есть, например: {list_phrase}. "
                "Уточните технику."
            ),
            "source": "1c",
        }
    if head == "ERROR":
        raise RuntimeError("1C request_part failed: " + "|".join(rest)[:400])
    if head not in ("B1", "B2", "B3", "B4"):
        raise RuntimeError(f"unexpected execute_code result: {data[:200]}")
    docs = {
        "B1": [rest[0]],
        "B2": [rest[0], rest[1]],
        "B3": [rest[0], rest[1], rest[2]],
        "B4": [rest[0]],
    }[head]
    return {
        "found": True,
        "vehicle": vehicle,
        "branch": head,
        "docs": docs,
        "quantity": qty,
        "message": _build_part_message(head, rest, vehicle, qty),
        "source": "1c",
    }
