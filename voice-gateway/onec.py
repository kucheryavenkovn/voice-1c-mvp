def _build_part_message(branch: str, fields: list, vehicle: str, qty: int) -> str:
    """Голосовое сообщение по результату request_part."""
    n = _plural(qty, "штука", "штуки", "штук")
    if branch == "B1":
        repair = fields[0]
        return (
            f"Запчасть есть на складе инженера. Создан заказ на ремонт № {repair}: "
            f"{fields[2]} — {qty} {n}, техника {fields[1]}."
        )
    if branch == "B2":
        repair, move = fields[0], fields[1]
        posted = len(fields) > 6 and fields[6].startswith("пров")
        tail = "" if posted else " Перемещение ожидает проведения в 1С."
        return (
            f"На складе инженера запчасти нет, но есть на складе текущего ОП "
            f"({fields[5]} шт). Создан заказ на ремонт № {repair} и перемещение № {move} "
            f"на склад инженера: {fields[3]} — {qty} {n}.{tail}"
        )
    if branch == "B3":
        repair, order_move, move = fields[0], fields[1], fields[2]
        posted = len(fields) > 7 and fields[7].startswith("пров")
        tail = "" if posted else " Перемещение ожидает проведения в 1С."
        return (
            f"Запчасть есть только на складе другого ОП ({fields[6]} шт). Создан заказ "
            f"на ремонт № {repair}, заказ на перемещение № {order_move} и перемещение "
            f"№ {move} на склад инженера: {fields[4]} — {qty} {n}.{tail}"
        )
    if branch == "B4":
        return (
            f"Запчасти ни на одном складе нет. Создан заказ поставщику № {fields[0]}: "
            f"{fields[2]} — {qty} {n}, для техники {fields[1]}."
        )
    return "; ".join(fields) if fields else vehicle


_SERVICE_WORDS = {"артикул", "код", "номер", "инв", "инв.", "инн", "номенклатура"}


def _strip_service(text: str) -> str:
    """Убрать служебные слова ('артикул 12345' -> '12345'), чтобы они не ломали
    поиск по токенам."""
    toks = [
        t
        for t in re.split(r"\s+", (text or "").strip())
        if t and t.lower().strip(".,!?") not in _SERVICE_WORDS
    ]
    return " ".join(toks)


def _fuzzy_pick(query: str, names: list, threshold: float = 0.6, limit: int = 3) -> list:
    """Приближённый подбор (опечатки/синонимы): ранжирование difflib.
    Сравнивается весь запрос с записью и каждый токен запроса с токенами записи.
    Порог ниже обычного — безопасно, т.к. лестница всегда подтверждает выбор."""
    import difflib

    def norm(s: str) -> str:
        return s.lower().replace("ё", "е")

    q = norm(query)
    q_toks = [t for t in re.split(r"\s+", q) if t]
    scored = []
    for n in names:
        nn = norm(n)
        n_toks = [t for t in re.split(r"\s+", nn) if t]
        score = difflib.SequenceMatcher(None, q, nn).ratio()
        for qt in q_toks:
            for nt in n_toks:
                score = max(score, difflib.SequenceMatcher(None, qt, nt).ratio())
        if score >= threshold:
            scored.append((score, n))
    scored.sort(reverse=True)
    return [n for _s, n in scored[:limit]]


