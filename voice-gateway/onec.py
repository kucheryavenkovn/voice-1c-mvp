def create_repair_order(items: list, vehicle_name: str) -> dict:
    """Создать по корзине: ОДИН ЗаказНаРемонт со всеми позициями + документы
    источников (перемещения, заказы на перемещение, заказ поставщику).
    items: [{'source':'E|C|O|S','part':{'name','article'},'qty':n}] (или плоские)."""
    norm = []
    for i in items:
        p = i.get("part") or {}
        norm.append(
            {
                "source": i["source"],
                "name": p.get("name") or i.get("name", ""),
                "article": p.get("article") or i.get("article", ""),
                "qty": i.get("qty", 1),
            }
        )
    items_str = "~".join(f"{i['source']}|{i['name']}|{i['article']}|{int(i['qty'])}" for i in norm)
    data = execute_code(_build_cart_code(items_str, vehicle_name))
    if data.startswith("ERROR"):
        raise RuntimeError("1C cart failed: " + data[6:400])
    if data.startswith("OK|"):
        data = data[3:]
    docs = {}
    for part in data.split(";"):
        if "=" in part:
            k, v = part.split("=", 1)
            docs[k.strip()] = v.strip()
    if "repair" not in docs:
        raise RuntimeError(f"unexpected execute_code result: {data[:200]}")
    return {"docs": docs, "message": _build_cart_message(norm, docs)}


def _build_cart_message(items: list, docs: dict) -> str:
    n = len(items)
    pos = _plural(n, "позиция", "позиции", "позиций")
    lst = "; ".join(
        f"{i['name']} (арт. {i['article']}) — {i['qty']} {_plural(i['qty'], 'штука', 'штуки', 'штук')}"
        for i in items
    )
    msg = f"Создан заказ на ремонт № {docs.get('repair')} ({n} {pos}: {lst})."
    tail = []
    if docs.get("cmove"):
        tail.append(
            f"Перемещение № {docs['cmove']} со склада текущего ОП оформлено (ожидает проведения)."
        )
    if docs.get("zorder") or docs.get("zmove"):
        z = ", ".join(
            x
            for x in (
                f"заказ на перемещение № {docs.get('zorder')}" if docs.get("zorder") else "",
                f"перемещение № {docs.get('zmove')}" if docs.get("zmove") else "",
            )
            if x
        )
        tail.append(f"Со склада другого ОП: {z} (ожидает проведения).")
    if docs.get("order"):
        tail.append(f"Под заказ поставщику: заказ № {docs['order']}.")
    return msg + " " + " ".join(tail)


