def _build_order_message(name: str, article: str, qty: int, number: str) -> str:
    """Голосовое подтверждение заказа: 'Создан заказ № …: Подушка — 3 штуки.
    Потребность зарегистрирована.'"""
    a = f" (арт. {article})" if article else ""
    n = _plural(qty, "штука", "штуки", "штук")
    return f"Создан заказ № {number}: {name}{a} — {qty} {n}. {ORDER_STATUS}."


def create_order(item: str, quantity: int) -> dict:
    """Создать заказ в 1С (execute_code). Контракт совместим с mock-api POST /api/orders:
    {item, found, quantity, order_number, status, message, source}.

    Ошибки записи (чёрный список `Записать`, обязательные поля ERP, …) возбуждают
    исключение — шлюз откатывается на mock-заказ."""
    if not _sanitize(item):
        return {
            "item": item,
            "found": False,
            "quantity": None,
            "order_number": None,
            "status": None,
            "message": f"Не удалось определить название товара '{item}'.",
            "source": "1c",
        }
    data = execute_code(_build_order_code(item, quantity))
    parts = data.split("|")
    qty = max(1, int(quantity))
    if parts and parts[0] == "NOTFOUND":
        return {
            "item": item,
            "found": False,
            "quantity": None,
            "order_number": None,
            "status": None,
            "message": f"Товар '{item}' не найден в справочнике 1С.",
            "source": "1c",
        }
    if parts and parts[0] == "ERROR":
        raise RuntimeError("1C order write failed: " + "|".join(parts[1:])[:300])
    if not parts or parts[0] != "OK" or len(parts) < 3:
        raise RuntimeError(f"unexpected execute_code result: {data[:200]}")
    number = parts[1].strip()
    name = parts[2].strip()
    article = parts[3].strip() if len(parts) > 3 else ""
    return {
        "item": item,
        "found": True,
        "quantity": qty,
        "order_number": number,
        "status": ORDER_STATUS,
        "message": _build_order_message(name, article, qty, number),
        "source": "1c",
    }


